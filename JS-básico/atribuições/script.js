// operadores de atribução são operadores que atribuem um valor a uma variável

// exemplo mais básico
let number = 1;

// operadores de incremento e decrementos são operadores de atribuição, especialmente utéis, pois executam atribuição e operação aritmética na mesma linha

// incrementa o valor do number + 10
number += 10
console.log(number)

// decrementa o valor do number - 10
number +- 10
console.log(number);

// além de adição e subtração, temos outras operações

// multiplica o valor do number * 10
number *= 10
console.log(number);

// divide o valor do number / 10
number /= 10
console.log(number);

// exponencia o valor do number ** 10
number **= 10
console.log(number);

// módulo (resto da divisão) do valor do number % 10
number %= 10
console.log(number);

