// array é uma coleção ordenada de valores (um após outro)
// os elementos são numerados de forma ordenada, começando do 0 até o total de elementos - 1
// Por exemplo, o primeiro elemento se encontra no índice 0, e o último elemento se encontra no índice mais alto + 1
// pois índice != tamanho de um array

const fruits = ["banana", "melancia", "maça", "uva", "goiaba"]

// primeiro elemento
console.log(fruits[0])

// todos os elementos na lista
console.log(fruits)
